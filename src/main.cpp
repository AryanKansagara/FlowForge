#include <algorithm>
#include <cstdint>
#include <filesystem>
#include <fstream>
#include <iostream>
#include <regex>
#include <sstream>
#include <stdexcept>
#include <string>
#include <vector>

namespace fs = std::filesystem;
struct Program { std::string name; int width = 0; std::vector<int> taps; };
int integer(const std::string& token) {
  std::size_t end = 0;
  try { const int value = std::stoi(token, &end); if (end == token.size()) return value; }
  catch (const std::exception&) {}
  throw std::runtime_error("invalid integer: " + token);
}
Program parse(const fs::path& path) {
  std::ifstream input(path); if (!input) throw std::runtime_error("cannot open specification");
  Program p; std::string line; bool has_taps = false; int number = 0;
  while (std::getline(input, line)) {
    ++number; line = line.substr(0, line.find('#')); std::istringstream row(line);
    std::string directive, token; if (!(row >> directive)) continue;
    try {
      if (directive == "fir") {
        if (!p.name.empty() || !(row >> token) || !std::regex_match(token, std::regex("[A-Za-z_][A-Za-z0-9_]{0,47}"))) throw std::runtime_error("expected one unique FIR identifier");
        p.name = token; if (row >> token) throw std::runtime_error("unexpected name argument");
      } else if (directive == "width") {
        if (p.width || !(row >> token)) throw std::runtime_error("expected one unique input width");
        p.width = integer(token); if (p.width < 8 || p.width > 16 || row >> token) throw std::runtime_error("width must be in [8,16]");
      } else if (directive == "taps") {
        if (has_taps) throw std::runtime_error("duplicate taps directive"); has_taps = true;
        while (row >> token) { const int coefficient = integer(token); if (coefficient < -128 || coefficient > 127) throw std::runtime_error("coefficients must fit signed int8"); p.taps.push_back(coefficient); }
        if (p.taps.empty() || p.taps.size() > 16) throw std::runtime_error("expected 1..16 coefficients");
      } else throw std::runtime_error("unknown directive: " + directive);
    } catch (const std::exception& e) { throw std::runtime_error("line " + std::to_string(number) + ": " + e.what()); }
  }
  if (p.name.empty() || !p.width || !has_taps) throw std::runtime_error("required directives: fir, width, taps");
  return p;
}
std::string literal(int value) { return value < 0 ? "(-64'sd" + std::to_string(-value) + ")" : "64'sd" + std::to_string(value); }
void compile(const Program& p, const fs::path& directory, bool optimize) {
  fs::create_directories(directory);
  std::ofstream rtl(directory / "filter.sv"), ir(directory / "ir.json");
  if (!rtl || !ir) throw std::runtime_error("cannot create output artifacts");
  rtl << "// Generated by FlowForge; synchronous active-high reset.\nmodule ff_" << p.name
      << "(input logic clk, rst, in_valid, input logic signed [" << p.width-1
      << ":0] sample_in, output logic out_valid, output logic signed [31:0] sample_out);\n";
  if (p.taps.size() > 1) rtl << "logic signed [" << p.width-1 << ":0] history [0:" << p.taps.size()-2 << "];\n";
  rtl << "wire signed [63:0] accumulator;\nassign accumulator = 64'sd0";
  int multiplies = 0;
  for (std::size_t i = 0; i < p.taps.size(); ++i) {
    const auto operand = i == 0 ? "sample_in" : "history[" + std::to_string(i-1) + "]";
    const int c = p.taps[i];
    if (optimize && c == 0) continue;
    if (optimize && (c == 1 || c == -1)) rtl << (c == 1 ? " + " : " - ") << "$signed(" << operand << ")";
    else { ++multiplies; rtl << " + ($signed(" << operand << ") * " << literal(c) << ")"; }
  }
  rtl << ";\nalways_ff @(posedge clk) begin\n  if (rst) begin\n    out_valid <= 0; sample_out <= 0;\n";
  for (std::size_t i=1; i<p.taps.size(); ++i) rtl << "    history[" << i-1 << "] <= 0;\n";
  rtl << "  end else begin\n    out_valid <= in_valid;\n    if (in_valid) begin\n      sample_out <= accumulator[31:0];\n";
  for (std::size_t i=p.taps.size()-1; i>0; --i) rtl << "      history[" << i-1 << "] <= " << (i==1 ? "sample_in" : "history["+std::to_string(i-2)+"]") << ";\n";
  rtl << "    end\n  end\nend\nendmodule\n";
  ir << "{\"name\":\"" << p.name << "\",\"input_bits\":" << p.width << ",\"output_bits\":32,\"accumulator_bits\":64,\"taps\":[";
  for (std::size_t i=0; i<p.taps.size(); ++i) ir << (i ? "," : "") << p.taps[i];
  ir << "],\"optimized\":" << (optimize ? "true" : "false") << ",\"source_multiply_operators\":" << multiplies << "}\n";
  if (!rtl || !ir) throw std::runtime_error("output write failed");
}
void model(const Program& p, const fs::path& path) {
  std::ifstream input(path); if (!input) throw std::runtime_error("cannot open sample file");
  std::vector<std::int64_t> history(p.taps.size(), 0); std::string token;
  const int limit = 1 << (p.width-1);
  while (input >> token) {
    const int sample = integer(token); if (sample < -limit || sample >= limit) throw std::runtime_error("sample outside configured signed input range");
    for (std::size_t i=history.size()-1; i>0; --i) history[i] = history[i-1];
    history[0] = sample; std::int64_t sum = 0;
    for (std::size_t i=0; i<p.taps.size(); ++i) sum += history[i] * p.taps[i];
    std::cout << sum << '\n';
  }
}
int main(int argc, char** argv) {
  try {
    if (argc < 4) throw std::runtime_error("usage: flowforge compile spec.fir output_dir [--baseline] | model spec.fir samples.txt");
    const std::string command = argv[1]; const auto program = parse(argv[2]);
    if (command == "compile" && (argc == 4 || (argc == 5 && std::string(argv[4]) == "--baseline"))) compile(program, argv[3], argc == 4);
    else if (command == "model" && argc == 4) model(program, argv[3]);
    else throw std::runtime_error("unknown command or arguments");
    return 0;
  } catch (const std::exception& e) { std::cerr << "flowforge: " << e.what() << '\n'; return 1; }
}
